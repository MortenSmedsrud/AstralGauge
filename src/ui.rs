fn level_banner(ui: &mut egui::Ui, level: Level, why: &str) {
    let (fill, stroke, text, title) = match level {
        Level::Red => (
            egui::Color32::from_rgb(69, 18, 18),
            palette::RED,
            egui::Color32::from_rgb(254, 202, 202),
            "CRITICAL CURRENT",
        ),
        _ => (
            egui::Color32::from_rgb(66, 52, 8),
            palette::YELLOW,
            egui::Color32::from_rgb(253, 230, 138),
            "HIGH CURRENT",
        ),
    };
    banner(ui, fill, stroke, |ui| {
        dot_label(
            ui,
            egui::RichText::new(title).strong().size(15.0).color(text),
            stroke,
        );
        ui.label(egui::RichText::new(why).size(14.0).color(text));
    });
}

/// The banner shown while the automatic power limit has the GPU powered
/// down: the lowered and the normal limit, and when it comes back.
fn power_down_banner(ui: &mut egui::Ui, pd: &PowerDown, sample: &Sample) {
    let text = egui::Color32::from_rgb(233, 213, 255);
    let applied = matches!((sample.limit_w, sample.limit_min_w), (Some(l), Some(min)) if l <= min);
    let title = match sample.limit_w {
        Some(limit) if applied => format!(
            "GPU POWERED DOWN \u{2014} power limit at the {limit} W minimum (normally {} W)",
            pd.saved_w
        ),
        // Requested, not (yet) in effect: the privileged helper may still be
        // waiting for its authentication.
        _ => format!(
            "POWERING DOWN \u{2014} lowering the power limit (normally {} W) to its minimum\u{2026}",
            pd.saved_w
        ),
    };
    let when = match pd.restore_in {
        Some(left) => format!("Restores to {} W in {:.0} s.", pd.saved_w, left.ceil()),
        None => format!(
            "Restores 30 s after every pin is back below {:.1} A.",
            pd.trigger_a
        ),
    };
    banner(
        ui,
        egui::Color32::from_rgb(46, 26, 74),
        palette::PDOWN,
        |ui| {
            dot_label(
                ui,
                egui::RichText::new(title).strong().color(text),
                palette::PDOWN,
            );
            ui.label(egui::RichText::new(when).color(text));
        },
    );
}

/// Rounded status chip ("● Live", "● Sensor fault") for the header.
///
/// Painted as one fixed-size widget (not a `Frame`), so a center-aligned
/// row centers it exactly like the buttons next to it.
fn status_pill(ui: &mut egui::Ui, text: &str, color: egui::Color32) -> egui::Response {
    let galley =
        ui.painter()
            .layout_no_wrap(text.to_owned(), egui::FontId::proportional(12.0), color);
    let (pad_x, dot, gap) = (10.0, 7.0, 5.0);
    let size = egui::vec2(pad_x * 2.0 + dot + gap + galley.size().x, 22.0);
    let (rect, response) = ui.allocate_exact_size(size, egui::Sense::hover());
    let painter = ui.painter();
    painter.rect_filled(
        rect,
        egui::CornerRadius::same(255),
        color.gamma_multiply(0.15),
    );
    let dot_center = egui::pos2(rect.left() + pad_x + dot / 2.0, rect.center().y);
    painter.circle_filled(dot_center, dot / 2.0, color);
    let text_pos = egui::pos2(
        rect.left() + pad_x + dot + gap,
        rect.center().y - galley.size().y / 2.0,
    );
    painter.galley(text_pos, galley, color);
    response
}

/// The strip under the header while this window shows the background
/// service's data: says so, and links the service's web interface.
fn service_banner(ui: &mut egui::Ui, link: &ServiceLink) {
    let incompatible = link.incompatible.is_some();
    let (fill, stroke) = if incompatible {
        (egui::Color32::from_rgb(58, 36, 14), palette::ORANGE)
    } else {
        (
            egui::Color32::from_rgb(20, 33, 52),
            egui::Color32::from_rgb(37, 64, 104),
        )
    };
    banner(ui, fill, stroke, |ui| {
        if incompatible {
            ui.label(
                egui::RichText::new(
                    "The background service runs a different build of AstralGauge, so its data \
                     cannot be shown here. Restart it in Settings \u{2192} Background service.",
                )
                .color(egui::Color32::from_rgb(253, 186, 116)),
            );
            return;
        }
        ui.label(
            egui::RichText::new("Running as a background service.")
                .strong()
                .color(palette::ACCENT),
        );
        ui.label(
            egui::RichText::new(
                "Monitoring, alert sounds and the safeguard keep running with this window \
                 closed; this window shows the service's data.",
            )
            .color(palette::TEXT),
        );
        match (link.web_port, &link.web_error) {
            (Some(port), _) => {
                let bind = link
                    .web_bind
                    .unwrap_or(std::net::IpAddr::V4(std::net::Ipv4Addr::UNSPECIFIED));
                let url = local_url(std::net::SocketAddr::new(bind, port));
                if ui
                    .link(
                        egui::RichText::new(format!("Web interface (port {port})"))
                            .color(palette::ACCENT)
                            .underline(),
                    )
                    .on_hover_text(format!("Open {url} in the browser"))
                    .clicked()
                {
                    ui.ctx().open_url(egui::OpenUrl::new_tab(url));
                }
            }
            (None, Some(e)) => {
                ui.label(
                    egui::RichText::new(format!("Web interface: {e} (retrying)"))
                        .color(palette::ORANGE),
                );
            }
            (None, None) => {}
        }
    });
}

